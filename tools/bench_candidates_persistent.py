"""Benchmark-only loaded process workers over read-only numerical mappings.

The parent owns financial cache coordination and completed-trial publication.
Children attach immutable inputs once, run the common Python candidate executor,
and never acquire the parent's cache lock or publish a result. Request tokens
clear child request state before the first job of every fresh request.
"""
import sys as _root_sys
from pathlib import Path as _RootPath
_root_sys.path.insert(0,str(_RootPath(__file__).resolve().parents[1]))
from backtest.inputs import research
from concurrent.futures import ProcessPoolExecutor, TimeoutError as FutureTimeout
from contextlib import suppress
from dataclasses import dataclass
import hashlib
import json
import multiprocessing
from multiprocessing.util import Finalize
import os
from pathlib import Path
import pickle
from queue import Empty
import shutil
import tempfile
from threading import Thread
import time

import numpy as np


FORMAT = 1
_worker_inputs = _worker_executor = _worker_request = None


def _hash(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def _policy_identity(policy):
    body = (policy.signature, tuple(policy.input_names), tuple(policy.output_names), tuple(policy.expressions))
    return hashlib.sha256(pickle.dumps(body, protocol=4)).hexdigest()


@dataclass(frozen=True)
class _ArrayReference:
    filename: str


def export_inputs(inputs, folder):
    """Save trusted prepared state and content-bound, non-object .npy buffers.

    Every array is stored once per distinct memory view. Module and generated
    function ownership stay in the caller; workers reconstruct the source-bound
    policy after acquiring shared runtime-source ownership.
    """
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=False)
    arrays, seen = {}, {}

    def freeze(value):
        if isinstance(value, np.ndarray):
            if value.dtype.hasobject:
                raise ValueError('Mapped numerical inputs cannot contain object arrays.')
            key = (value.__array_interface__['data'][0], value.shape, value.strides, value.dtype.str)
            if key not in seen:
                filename = f'buffer-{len(seen):04}.npy'
                np.save(folder / filename, value, allow_pickle=False)
                arrays[filename] = dict(sha256=_hash(folder / filename), dtype=value.dtype.str,
                                        shape=list(value.shape), bytes=(folder / filename).stat().st_size)
                seen[key] = _ArrayReference(filename)
            return seen[key]
        if isinstance(value, dict):
            return {key: freeze(item) for key, item in value.items()}
        if isinstance(value, tuple):
            return tuple(freeze(item) for item in value)
        if isinstance(value, list):
            return [freeze(item) for item in value]
        return value

    state = {key: freeze(value) for key, value in vars(inputs).items() if key not in ('s', 'policy')}
    metadata = folder / 'state.pickle'
    with metadata.open('wb') as handle:
        pickle.dump(state, handle, protocol=5)
    manifest = dict(format=FORMAT, state='state.pickle', state_sha256=_hash(metadata),
                    arrays=arrays, policy_sha256=_policy_identity(inputs.policy),
                    runtime=str(Path(research.ROOT).resolve()))
    path = folder / 'manifest.json'
    path.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    return path


def open_inputs(manifest_path, schedules):
    """Reattach only this module's trusted export, with read-only mapped arrays."""
    from bench_candidates import NumericInputs, PolicyProgram
    manifest_path = Path(manifest_path).resolve()
    folder = manifest_path.parent
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    if manifest.get('format') != FORMAT:
        raise ValueError('Unsupported mapped candidate input format.')
    if manifest.get('state') != 'state.pickle':
        raise ValueError('Mapped candidate metadata has an invalid path.')
    metadata = folder / manifest['state']
    if _hash(metadata) != manifest['state_sha256']:
        raise ValueError('Mapped candidate metadata changed.')
    # This file is generated by export_inputs under the parent's owned temp
    # directory. It is not a public import or an untrusted-file format.
    with metadata.open('rb') as handle:
        state = pickle.load(handle)
    opened = {}

    def thaw(value):
        if isinstance(value, _ArrayReference):
            name = value.filename
            if name not in manifest['arrays'] or Path(name).name != name:
                raise ValueError('Mapped candidate buffer has an invalid path.')
            if name not in opened:
                expected = manifest['arrays'][name]
                path = folder / name
                if _hash(path) != expected['sha256']:
                    raise ValueError('Mapped candidate buffer content changed.')
                array = np.load(path, mmap_mode='r', allow_pickle=False)
                if array.dtype.str != expected['dtype'] or list(array.shape) != expected['shape']:
                    array._mmap.close()
                    raise ValueError('Mapped candidate buffer shape or dtype changed.')
                opened[name] = array
            return opened[name]
        if isinstance(value, dict):
            return {key: thaw(item) for key, item in value.items()}
        if isinstance(value, tuple):
            return tuple(thaw(item) for item in value)
        if isinstance(value, list):
            return [thaw(item) for item in value]
        return value

    try:
        result = NumericInputs.__new__(NumericInputs)
        result.__dict__.update(thaw(state))
        result.s = schedules
        result.policy = PolicyProgram(bankrupt=result.bankrupt)
        if _policy_identity(result.policy) != manifest['policy_sha256']:
            raise ValueError('Mapped candidate policy differs from current source.')
        result._persistent_mappings = tuple(opened.values())
        return result
    except BaseException:
        for array in opened.values():
            with suppress(Exception):
                array._mmap.close()
        raise


def close_inputs(inputs):
    """Close owned mappings after all calculations have returned."""
    for array in getattr(inputs, '_persistent_mappings', ()):
        with suppress(Exception):
            array._mmap.close()
    inputs._persistent_mappings = ()


def _worker_close():
    global _worker_inputs, _worker_executor
    if _worker_executor is not None:
        _worker_executor.close()
        _worker_executor = None
    if _worker_inputs is not None:
        close_inputs(_worker_inputs)
        _worker_inputs = None


def _worker_initialize(manifest_path, runtime, limits, ready):
    global _worker_inputs, _worker_executor, _worker_request
    # No production module is imported before this bootstrap owns runtime source.
    import bench_baseline as baseline
    baseline.bootstrap(runtime)
    from bench_candidates import PythonExecutor
    parent = multiprocessing.parent_process()
    if parent is not None:
        def follow_parent():
            parent.join()
            os._exit(0)
        Thread(target=follow_parent, daemon=True).start()
    try:
        _worker_inputs = open_inputs(manifest_path, baseline.s)
        _worker_executor = PythonExecutor(_worker_inputs, policy=_worker_inputs.policy, limits=limits)
        _worker_request = None
        Finalize(None, _worker_close, exitpriority=20)
        ready.put(dict(pid=os.getpid()))
    except BaseException as error:
        ready.put(dict(pid=os.getpid(), error_type=type(error).__name__))
        _worker_close()
        raise


def _worker_ping():
    return os.getpid()


def _worker_evaluate(token, request, books, options, capture):
    global _worker_request
    if token != _worker_request:
        _worker_executor.begin(request)
        _worker_request = token
    _worker_executor.limits['capture'] = bool(capture)
    before = dict(getattr(_worker_executor, 'stats', {}))
    result = _worker_executor.evaluate(books, options=options)
    after = dict(getattr(_worker_executor, 'stats', {}))
    counters = {key: value - before.get(key, 0.) for key, value in after.items()
                if isinstance(value, (int, float)) and isinstance(before.get(key, 0.), (int, float))}
    trace = getattr(_worker_executor, 'trace', None)
    return result, counters, trace


class PersistentExecutor:
    """Keep bounded spawned Python executors attached across fresh requests."""

    def __init__(self, inputs, policy=None, limits=None):
        self.inputs = inputs
        self.policy = policy or inputs.policy
        if _policy_identity(self.policy) != _policy_identity(inputs.policy):
            raise ValueError('Persistent executor requires the attached source policy.')
        self.limits = dict(limits or {})
        self._closed = False
        self._pool = None
        self._request = None
        self._token = 0
        self.trace = {}
        self.deadline = None
        began = time.perf_counter()
        count = self.limits.get('workers', self.limits.get('threads', 4))
        if type(count) is not int or not 1 <= count <= 4:
            raise ValueError('Persistent candidate workers must be between one and four.')
        self.workers = min(count, os.cpu_count() or 1)
        self.stats = dict(workers=self.workers, requests=0, batches=0, worker_jobs=0,
                          worker_pids=[], backend='persistent',
                          coverage='Persistent loaded Python candidate executors over read-only mapped inputs.')
        workdir = self.limits.get('workdir')
        if workdir is None:
            workdir = Path(research.ROOT) / 'tmp/cb02-candidates/persistent'
        workdir = Path(workdir)
        workdir.mkdir(parents=True, exist_ok=True)
        self._directory = Path(tempfile.mkdtemp(prefix='workers-', dir=workdir))
        self._ready = multiprocessing.get_context('spawn').Queue()
        try:
            manifest = export_inputs(inputs, self._directory / 'inputs')
            self.stats['mapped_bytes'] = sum(path.stat().st_size for path in (self._directory / 'inputs').iterdir())
            context = multiprocessing.get_context('spawn')
            child_limits = dict(self.limits)
            child_limits['workers'] = child_limits['threads'] = 1
            self._pool = ProcessPoolExecutor(max_workers=self.workers, mp_context=context,
                initializer=_worker_initialize,
                initargs=(str(manifest), str(research.ROOT), child_limits, self._ready))
            pings = [self._pool.submit(_worker_ping) for unused in range(self.workers)]
            setup_budget = float(self.limits.get('setup_seconds', 600.))
            deadline = began + setup_budget
            for unused in range(self.workers):
                try:
                    ready = self._ready.get(timeout=max(.01, deadline-time.perf_counter()))
                except Empty as error:
                    raise TimeoutError('Persistent worker attachment exceeded setup budget.') from error
                if ready.get('error_type'):
                    raise RuntimeError('Persistent worker initialization failed: '+ready['error_type'])
                self.stats['worker_pids'].append(ready['pid'])
            for future in pings:
                future.result(timeout=max(.01, deadline-time.perf_counter()))
            self.stats['setup_seconds'] = time.perf_counter()-began
        except BaseException:
            self.close()
            raise

    def begin(self, request):
        if self._closed:
            raise RuntimeError('Persistent candidate executor is closed.')
        self._token += 1
        self._request = request
        self.trace = {}
        self.deadline = None
        self.stats['requests'] += 1
        for key in tuple(self.stats):
            if key.startswith('worker_') and key != 'worker_pids':
                self.stats.pop(key)
        self.stats['batches'] = self.stats['worker_jobs'] = 0

    def evaluate(self, book_batch, options=None):
        if self._closed:
            raise RuntimeError('Persistent candidate executor is closed.')
        if self._request is None:
            raise RuntimeError('Begin a fresh request before evaluating candidates.')
        books = list(book_batch)
        self.trace = {}
        if not books:
            return []
        deadline = self.deadline or self.limits.get('deadline')
        if deadline is not None and time.perf_counter() > deadline:
            raise TimeoutError('Persistent candidate batch exceeded request budget.')
        # A bounded caller batch is split into at most one task per worker.
        # No executor maintains an unbounded prefetch queue across requests.
        size = max(1, (len(books)+self.workers-1)//self.workers)
        pending = [self._pool.submit(_worker_evaluate, self._token, self._request,
                                    books[index:index+size], options,bool(self.limits.get('capture')))
                   for index in range(0, len(books), size)]
        result, traces = [], []
        book_offset = 0
        try:
            for future in pending:
                while True:
                    try:
                        rows, counters, trace = future.result(timeout=.25)
                        break
                    except FutureTimeout:
                        deadline = self.deadline or self.limits.get('deadline')
                        if deadline is not None and time.perf_counter() > deadline:
                            raise TimeoutError('Persistent candidate batch exceeded request budget.')
                result.extend(rows)
                for key, value in counters.items():
                    self.stats['worker_'+key] = self.stats.get('worker_'+key, 0.)+value
                if trace:
                    adjusted = dict(trace)
                    adjusted['row_books'] = adjusted['row_books']+book_offset
                    traces.append(adjusted)
                book_offset += len(rows)
            self.stats['batches'] += 1
            self.stats['worker_jobs'] += len(pending)
            if traces:
                self.trace = {key: np.concatenate([trace[key] for trace in traces], axis=0)
                              for key in traces[0]}
            return result
        finally:
            # An interrupted call must not let work escape its financial owner.
            for future in pending:
                if not future.done():
                    future.cancel()
            for future in pending:
                if not future.cancelled():
                    with suppress(Exception):
                        future.result()

    def close(self):
        if self._closed:
            return
        self._closed = True
        if self._pool is not None:
            self._pool.shutdown(wait=True, cancel_futures=True)
            self._pool = None
        if hasattr(self, '_ready'):
            self._ready.close()
            self._ready.join_thread()
        if hasattr(self, '_directory'):
            try:
                shutil.rmtree(self._directory)
            except OSError as error:
                self.stats['cleanup_error_type'] = type(error).__name__


def attach(inputs, policy=None, limits=None):
    """Attach immutable inputs once; caller retains cache ownership to close()."""
    return PersistentExecutor(inputs, policy=policy, limits=limits)
